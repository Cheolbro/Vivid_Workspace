function applyGlobalStyleAnchor(promptBody, catalog) {
  const anchor = catalog.global_style_anchor && catalog.global_style_anchor.anchor_text;
  if (!anchor) return promptBody;
  if (promptBody.toLowerCase().includes(anchor.toLowerCase())) return promptBody;
  return `${promptBody.trim()}, ${anchor}`;
}

