const items = $input.all();
if (!items || items.length === 0) throw new Error("[Node 4] 입력 아이템 없음");

const node1 = $("Load Files").first().json;
const VIDEO_ID = node1.video_id;
const PROJECT_ROOT = node1.project_root;
if (!VIDEO_ID) throw new Error("[Node 4] video_id 누락");
if (!PROJECT_ROOT) throw new Error("[Node 4] project_root 누락");

const promptsDir = path.join(PROJECT_ROOT, "asset_prompts");
fs.mkdirSync(promptsDir, { recursive: true });

const allItems = [];
for (const item of items) {
  const j = item.json || {};
  if (!j.chapter_id || !j.plan_path) throw new Error("[Node 4] chapter_id/plan_path 누락");

  const catalogPath =
    j.catalog_path ||
    path.resolve(__dirname, "..", "..", "shared_assets", "references_catalog.json");
  if (!fs.existsSync(catalogPath)) throw new Error(`[Node 4] catalog 누락: ${catalogPath}`);
  if (!fs.existsSync(j.plan_path)) throw new Error(`[Node 4] plan 누락: ${j.plan_path}`);

  // 과제 11: hnswlib 인덱스 파일 (Node 9.5와 동일 위치)
  const indexPath =
    j.index_path || path.resolve(__dirname, "..", "..", "shared_assets", "references_catalog.idx");

  const promptsCachePath = path.join(promptsDir, `${j.chapter_id}_prompts.json`);
  if (fs.existsSync(promptsCachePath)) {
    const cached = JSON.parse(fs.readFileSync(promptsCachePath, "utf-8"));
    for (const a of cached) allItems.push({ json: a });
    continue;
  }

  const plan = JSON.parse(fs.readFileSync(j.plan_path, "utf-8"));
  const catalog = JSON.parse(fs.readFileSync(catalogPath, "utf-8"));

  const prompt = buildPrompt(plan, catalog);
  const geminiOutput = callGeminiCli(prompt);
  const enriched = postProcessAssets(geminiOutput, catalog, VIDEO_ID, { indexPath });

  const errors = validateAssets(enriched);
  if (errors.length > 0) {
    throw new Error(`[Node 4][${j.chapter_id}] 검증 실패:\n  - ${errors.join("\n  - ")}`);
  }

  fs.writeFileSync(promptsCachePath, JSON.stringify(enriched, null, 2), "utf-8");
  for (const a of enriched) allItems.push({ json: a });
}

return allItems;
