function callGeminiCli(prompt, retries = 3) {
  for (let attempt = 1; attempt <= retries; attempt++) {
    const result = spawnSync("gemini", ["--prompt", prompt, "--format", "json"], {
      encoding: "utf-8",
      maxBuffer: 50 * 1024 * 1024,
      timeout: 180000,
    });
    if (result.status === 0 && result.stdout) {
      try {
        return JSON.parse(
          result.stdout
            .trim()
            .replace(/^```json\s*/, "")
            .replace(/```$/, "")
        );
      } catch (e) {
        if (attempt === retries) throw new Error(`[Node 4] JSON 파싱 실패: ${e.message}`);
      }
    } else if (attempt === retries) {
      throw new Error(`[Node 4] Gemini CLI 실패: ${result.stderr || "unknown"}`);
    }
  }
}

