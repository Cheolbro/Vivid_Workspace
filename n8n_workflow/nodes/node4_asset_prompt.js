/**
 * Node 4 — Asset Prompt Engineer (Gemini CLI 호출)
 *
 * 목적: Node 3 plan + references_catalog.json → ComfyUI(FLUX) 프롬프트 산출.
 *      5계층 카테고리 검색(W-1, W-3) + 임베딩 검색(BN-5) + 캐시 재사용 결정.
 *
 * v4.5 신규:
 *   - 5계층 검색 우선순위 (characters → static_assets → auto_generated_assets → props → 신규)
 *   - description_search(임베딩 인풋, 화풍 토큰 제거) / description_render(ComfyUI 인풋, 화풍 앵커 포함) 분리
 *   - 글로벌 화풍 앵커 코드 강제 suffix 주입
 *   - hnswlib 코사인 검색 (처음부터 도입, sentence-transformers/all-MiniLM-L6-v2 384차원)
 *   - reuse_asset_id 매칭 시 L1 캐시 합류 → ComfyUI 호출 스킵
 *   - search_log 출력 강제 (5계층 시도 결과 명시 기록)
 *
 * v5.0 멀티 포맷 Multi-Sourcing 지원:
 *   - character_style: "silhouette" → 프롬프트에 실루엣 강제어 주입
 *   - bg_style: "b_roll_video" → ComfyUI 스킵, Pexels API 분기 메타 부여 (source_api: "pexels")
 *   - bg_style: "real_photo" → ComfyUI 스킵, Pixabay API 분기 메타 부여 (source_api: "pixabay")
 *   - bg_style: "solid_color" → 배경 에셋 생성 전면 스킵 (GPU 절약)
 *   - bg_style: "illustration" → 기존 ComfyUI 파이프라인 유지
 *
 * 시드 정책 (EF-1):
 *   - 캐릭터/소품: SHA1(video_id + ref_image_id)의 32-bit 해시 (영상 1편 내 동일 시드)
 *   - 배경/전경: 씬 단위 시드 (scene_id 기반)
 *
 * 입력 (n8n items[].json):
 *   - chapter_id: string
 *   - plan_path: string
 *   - catalog_path: string (shared_assets/references_catalog.json)
 *
 * 워크플로우 전역:
 *   - $('Load Files').first().json.video_id
 *   - $('Load Files').first().json.project_root
 *
 * 출력 (씬별 1 아이템):
 *   - { chapter_id, scene_id, asset_prompts: [...], search_log: [...] }
 *   - asset_prompts 배열은 Node 5에서 split 후 Node 6 Switch로 분기.
 *
 * 환경: gemini CLI + python(임베딩) 시스템 PATH 가용.
 */

