function sha1Hex(s) {
  return crypto.createHash("sha1").update(s).digest("hex");
}

function seedForAsset(assetType, videoId, refImageId, sceneId) {
  if (assetType === "character" || assetType === "prop") {
    const h = sha1Hex(`${videoId}|${refImageId}`);
    return parseInt(h.slice(0, 8), 16) >>> 0;
  } else {
    // background / foreground: 씬 단위 시드
    const h = sha1Hex(`${videoId}|${sceneId}|${assetType}`);
    return parseInt(h.slice(0, 8), 16) >>> 0;
  }
}

