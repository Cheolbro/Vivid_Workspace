// ──────────────────────────────────────────────
// 5계층 카테고리 검색
// ──────────────────────────────────────────────

const MATCH_SCORE_THRESHOLD = 0.7;
const EMBEDDING_THRESHOLD = embeddingSearch.constants.EMBEDDING_THRESHOLD;

function searchCatalog(catalog, query, opts = {}) {
  // query: { type, scene_pose_desc, scene_context, target_object_desc, tags, description_search }
  // opts:  { indexPath } — 과제 11 hnswlib 인덱스 경로 (있으면 그래프 탐색, 없으면 직접 코사인 폴백)
  const log = [];

  // tier 1: characters
  if (query.type === "character") {
    for (const [key, c] of Object.entries(catalog.characters || {})) {
      if (key.startsWith("_")) continue;
      const score = scoreCharacterMatch(c, query);
      log.push({ category: "characters", asset_id: key, score });
      if (score >= MATCH_SCORE_THRESHOLD) {
        return { hit: { tier: 1, category: "characters", asset_id: key, entry: c, score }, log };
      }
    }
  }

  // tier 2: static_assets (정확 ID 매칭만 — 임베딩 X)
  if (query.exact_static_id) {
    const sa = (catalog.static_assets || {})[query.exact_static_id];
    if (sa) {
      log.push({ category: "static_assets", asset_id: query.exact_static_id, score: 1.0 });
      return {
        hit: {
          tier: 2,
          category: "static_assets",
          asset_id: query.exact_static_id,
          entry: sa,
          score: 1.0,
        },
        log,
      };
    }
    log.push({ category: "static_assets", asset_id: query.exact_static_id, score: 0 });
  }

  // tier 3: auto_generated_assets — 과제 11 공용 레이어 위임 (hnswlib + 태그 폴백)
  if (query.description_search) {
    const r = embeddingSearch.searchAutoGenerated({
      catalog,
      indexPath: opts.indexPath,
      query: { description_search: query.description_search, tags: query.tags || [] },
      embedFn: opts.embedFn || embedTexts,
    });
    if (r.hit) {
      log.push({
        category: "auto_generated_assets",
        asset_id: r.hit.asset_id,
        score: r.hit.score,
        source: r.hit.source,
      });
      return {
        hit: {
          tier: 3,
          category: "auto_generated_assets",
          asset_id: r.hit.asset_id,
          entry: r.hit.entry,
          score: r.hit.score,
          source: r.hit.source,
        },
        log,
      };
    }
    if (r.log) {
      log.push({
        category: "auto_generated_assets",
        asset_id: null,
        score: r.log.top_sim || 0,
        reason: r.log.reason || "no_match",
      });
    }
  }

  // tier 4: props (img2img, match_score 기반)
  if (query.type === "prop") {
    for (const [key, p] of Object.entries(catalog.props || {})) {
      if (key.startsWith("_")) continue;
      const score = scorePropMatch(p, query);
      log.push({ category: "props", asset_id: key, score });
      if (score >= MATCH_SCORE_THRESHOLD) {
        return { hit: { tier: 4, category: "props", asset_id: key, entry: p, score }, log };
      }
    }
  }

  // tier 5: generate_asset:true 폴백
  log.push({ category: "generate_new", asset_id: null, score: 0 });
  return { hit: null, log };
}

function scoreCharacterMatch(c, query) {
  if (!query.scene_pose_desc) return 0;
  // 단순 키워드/태그 일치 비율
  const haystack = (c.appearance_anchor + " " + (c.tags || []).join(" ")).toLowerCase();
  const needles = (query.scene_pose_desc + " " + (query.scene_context || ""))
    .toLowerCase()
    .split(/\s+/);
  let hit = 0;
  for (const n of needles) if (n.length > 2 && haystack.includes(n)) hit++;
  return Math.min(1.0, hit / Math.max(3, needles.length / 2));
}

function scorePropMatch(p, query) {
  if (!query.target_object_desc) return 0;
  const haystack = (p.description + " " + (p.tags || []).join(" ")).toLowerCase();
  const needles = query.target_object_desc.toLowerCase().split(/\s+/);
  let hit = 0;
  for (const n of needles) if (n.length > 2 && haystack.includes(n)) hit++;
  return Math.min(1.0, hit / Math.max(2, needles.length / 2));
}

