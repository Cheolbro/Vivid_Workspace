function validateAssets(assets) {
  const errors = [];
  for (let i = 0; i < assets.length; i++) {
    const a = assets[i];
    const tag = `assets[${i}]`;
    if (!["character", "prop", "background", "foreground"].includes(a.asset_type))
      errors.push(`${tag}.asset_type 형식 오류: ${a.asset_type}`);
    if (!a.scene_asset_id) errors.push(`${tag}.scene_asset_id 누락`);
    if (!a.region_id) errors.push(`${tag}.region_id 누락 (MO-5)`);
    if (!a.description_search) errors.push(`${tag}.description_search 누락 (임베딩 인풋)`);
    if (!a.description_render) errors.push(`${tag}.description_render 누락 (ComfyUI 인풋)`);
    if (!Array.isArray(a.search_log)) errors.push(`${tag}.search_log 배열 누락 (W-1)`);
    if (typeof a.seed !== "number") errors.push(`${tag}.seed 누락`);

    // character/prop transparent PNG 강제어 검증
    if (["character", "prop", "foreground"].includes(a.asset_type)) {
      if (
        !a.description_render.toLowerCase().includes("isolated") &&
        !a.description_render.toLowerCase().includes("transparent")
      ) {
        errors.push(
          `${tag}.description_render에 transparent PNG 지시어 누락 (asset_type=${a.asset_type})`
        );
      }
    }
    if (a.asset_type === "background") {
      if (
        a.description_render.toLowerCase().includes("isolated") ||
        a.description_render.toLowerCase().includes("transparent")
      ) {
        errors.push(`${tag}.description_render에 transparent 지시어 금지 (background)`);
      }
    }
  }
  return errors;
}

