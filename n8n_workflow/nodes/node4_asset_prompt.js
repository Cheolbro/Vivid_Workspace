function postProcessAssets(geminiOutput, catalog, videoId, opts = {}) {
  const enriched = [];
  for (const sc of geminiOutput.scenes || []) {
    // V5.0: 씬 레벨 포맷 속성 추출 (Node 3 출력)
    const sceneData = {
      bg_style: sc.bg_style || "illustration",
      character_style: sc.character_style || "webtoon",
      foreground_style: sc.foreground_style || "none",
      overlay_focus: sc.overlay_focus || "none",
      search_query: sc.search_query || null,
    };

    // V5.0: bg_style가 "solid_color"이면 배경 에셋 생성 스킵 (GPU 절약)
    const skipBgGeneration = sceneData.bg_style === "solid_color";
    // V5.0: bg_style가 "b_roll_video" 또는 "real_photo"이면 ComfyUI 대신 API 라우팅
    const apiSourceBg = sceneData.bg_style === "b_roll_video" ? "pexels"
                      : sceneData.bg_style === "real_photo" ? "pixabay"
                      : null;

    for (const ap of sc.asset_prompts || []) {
      // V5.0: 배경 에셋에 대한 분기 처리
      if (ap.asset_type === "background") {
        if (skipBgGeneration) {
          // solid_color → 에셋 생성 전면 스킵, CSS만으로 처리
          enriched.push({
            chapter_id: geminiOutput.chapter_id,
            scene_id: sc.scene_id,
            asset_type: "background",
            scene_asset_id: ap.scene_asset_id || "background",
            region_id: ap.region_id || "default",
            skip_comfyui: true,
            source_api: null,
            bg_style: "solid_color",
            character_style: sceneData.character_style,
            foreground_style: sceneData.foreground_style,
            overlay_focus: sceneData.overlay_focus,
            search_query: null,
            search_log: [{ category: "solid_color_skip", asset_id: null, score: 0 }],
          });
          continue;
        }
        if (apiSourceBg) {
          // b_roll_video → Pexels API / real_photo → Pixabay API
          enriched.push({
            chapter_id: geminiOutput.chapter_id,
            scene_id: sc.scene_id,
            asset_type: "background",
            scene_asset_id: ap.scene_asset_id || "background",
            region_id: ap.region_id || "default",
            skip_comfyui: true,
            source_api: apiSourceBg,
            bg_style: sceneData.bg_style,
            character_style: sceneData.character_style,
            foreground_style: sceneData.foreground_style,
            overlay_focus: sceneData.overlay_focus,
            search_query: sceneData.search_query,
            search_log: [{ category: `api_${apiSourceBg}`, asset_id: null, score: 0 }],
          });
          continue;
        }
      }
      // 카탈로그 검색 (과제 11: tier-3은 indexPath로 hnswlib 그래프 탐색)
      const searchQuery = {
        type: ap.asset_type,
        scene_pose_desc: ap.description_search,
        scene_context: ap.description_render,
        target_object_desc: ap.description_search,
        description_search: ap.description_search,
        tags: ap.tags || [],
        exact_static_id: ap.exact_static_id,
      };
      const { hit, log } = searchCatalog(catalog, searchQuery, { indexPath: opts.indexPath });

      // reuse_asset_id 결정
      let reuse_asset_id = null;
      let generate_asset = false;
      let ref_image_id = "none";
      if (hit) {
        if (hit.tier === 1 || hit.tier === 4) {
          // characters / props → ref_image_id 사용 (FaceID/img2img 강제)
          ref_image_id = hit.entry.variants
            ? Object.values(hit.entry.variants)[0].ref_image_id
            : hit.entry.ref_image_id;
        } else {
          // static / auto_generated → reuse_asset_id (ComfyUI 스킵, L1 합류)
          reuse_asset_id = hit.asset_id;
        }
      } else {
        generate_asset = true;
      }

      // 글로벌 화풍 앵커 코드 강제 suffix
      let renderPrompt = applyGlobalStyleAnchor(ap.description_render, catalog);

      // ── V5.0: character_style "silhouette" → 프롬프트 강제 변환 ──
      if (sceneData.character_style === "silhouette" && ap.asset_type === "character") {
        renderPrompt = `pure black solid silhouette, flat vector shape, white background, ${renderPrompt}`;
      }

      // 시드 결정
      const seed = seedForAsset(ap.asset_type, videoId, ref_image_id, sc.scene_id);

      enriched.push({
        chapter_id: geminiOutput.chapter_id,
        scene_id: sc.scene_id,
        asset_type: ap.asset_type,
        scene_asset_id: ap.scene_asset_id,
        region_id: ap.region_id || "default",
        description_search: ap.description_search,
        description_render: renderPrompt,
        tags: ap.tags || [],
        pose: ap.pose || "auto",
        position: ap.position || "center",
        ref_image_id,
        reuse_asset_id,
        generate_asset,
        seed,
        lora_signature: catalog.global_style_anchor
          ? `noir_webtoon_style@${catalog.global_style_anchor.version}`
          : "noir_webtoon_style",
        search_log: log,
        // ── V5.0 멀티 포맷 메타 (Node 6/7 라우팅용) ──
        bg_style: sceneData.bg_style || "illustration",
        character_style: sceneData.character_style || "webtoon",
        foreground_style: sceneData.foreground_style || "none",
        overlay_focus: sceneData.overlay_focus || "none",
        search_query: sceneData.search_query || null,
      });
    }
  }
  return enriched;
}

